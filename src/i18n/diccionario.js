export function etiquetaCategoria(valor, t) {
  const clave = CATEGORIAS[valor];
  return clave ? t(clave) : (valor || '');
}

/** Locale para fechas según el idioma activo. */
export function localeDeIdioma(idioma) {
  return idioma === 'en' ? 'en-US' : 'es-SV';
}

/**
 * Crea la función traductora para un idioma dado.
 *
 * Admite interpolación simple:
 *   t('fin.sobrecostoDetalle', { gastado: '$1,000' })
 * sustituye cada {gastado} de la plantilla por su valor.
 */
export function crearTraductor(idioma) {
  const activo = DICCIONARIO[idioma] || DICCIONARIO.es;

  return function t(clave, params) {
    let texto;
    if (clave in activo) texto = activo[clave];
    else if (clave in DICCIONARIO.es) texto = DICCIONARIO.es[clave];
    else return clave;

    if (!params) return texto;

    return texto.replace(/\{(\w+)\}/g, (coincidencia, nombre) =>
      Object.prototype.hasOwnProperty.call(params, nombre) ? String(params[nombre]) : coincidencia
    );
  };
}

/**
 * Traduce el estado de un proyecto que viene de Supabase.
 *
 * El estado es dato de la base, pero en la práctica es un catálogo cerrado y
 * corto, así que se mapea a una clave. Si llega un valor no previsto se
 * devuelve tal cual: nunca se oculta información del usuario.
 */
const ESTADOS = {
  'en progreso': 'estado.enProgreso',
  'progreso': 'estado.enProgreso',
  'planificacion': 'estado.planificacion',
  'en planificacion': 'estado.planificacion',
  'en ejecucion': 'estado.enEjecucion',
  'ejecucion': 'estado.enEjecucion',
  'fase inicial': 'estado.faseInicial',
  'inicial': 'estado.faseInicial',
  'entregado': 'estado.entregado',
  'completado': 'estado.completado',
  'activo': 'estado.activo',
  'pausado': 'estado.pausado',
  'en revision': 'estado.enRevision',
  'finalizado': 'estado.finalizado',
  'finalizada': 'estado.finalizado',
  'finished': 'estado.finalizado'
};

export function etiquetaEstado(estado, t) {
  const bruto = String(estado ?? '').trim();
  if (!bruto) return '';

  // Supabase guarda estos valores en snake_case ('en_progreso', 'fase_inicial').
  // Se normalizan acentos, guiones bajos, guiones y espacios repetidos para que
  // 'en_progreso', 'En Progreso' y 'EN-PROGRESO' lleguen todos a la misma clave.
  const normalizado = bruto
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();

  const clave = ESTADOS[normalizado];
  if (clave) return t(clave);

  // Valor desconocido: se muestra legible, sin guiones bajos y con solo la
  // primera letra en mayúscula ('en_progreso' -> 'En progreso').
  return formatearEstado(bruto);
}

